# Gedeelde hulp voor de nep-programma's: echte jpg's maken, zodat je ze in de browser kunt openen.
#   pdf_to_jpg($pdf, $out, $hoogte)   eerste pagina van een pdf als jpg met die hoogte
#   shrink_jpg($in, $out, $max)       verkleinen tot hoogstens $max pixels (nooit opschalen); zonder gereedschap een kopie
# Gereedschap in deze volgorde: pdftoppm (ook als de PATH van de app er niet naar wijst: bekende mappen worden geprobeerd),
# sips (macOS, zit er standaard op) en als laatste een kleine echte jpg die in dit bestand zit.
package MockImage;
use strict; use warnings; use File::Copy qw(copy); use MIME::Base64 qw(decode_base64);
use Exporter 'import'; our @EXPORT_OK = qw(pdf_to_jpg shrink_jpg find_tool);

sub find_tool {
  my ($name) = @_;
  for my $d (split(/:/, $ENV{PATH} // ''), '/opt/homebrew/bin', '/usr/local/bin', '/usr/bin') {
    return "$d/$name" if -x "$d/$name";
  }
  return;
}

sub placeholder_jpg {
  my ($out) = @_;
  open(my $fh, '>:raw', $out) or die "kan $out niet schrijven: $!"; print $fh decode_base64(do { local $/; <DATA> }); close $fh;
}

sub pdf_to_jpg {
  my ($pdf, $out, $height) = @_;
  if (my $p = find_tool('pdftoppm')) {
    my $tmp = "$out.tmp";
    if (system($p, '-jpeg', '-f', '1', '-l', '1', '-singlefile', '-scale-to-y', $height, '-scale-to-x', '-1', $pdf, $tmp) == 0 && -s "$tmp.jpg") { rename("$tmp.jpg", $out); return 'pdftoppm'; }
  }
  if (my $s = find_tool('sips')) {
    if (system("\"$s\" -s format jpeg \"$pdf\" --out \"$out\" >/dev/null 2>&1") == 0 && -s $out) {
      system("\"$s\" -Z $height \"$out\" >/dev/null 2>&1");
      return 'sips';
    }
  }
  placeholder_jpg($out);
  return 'voorbeeldafbeelding';
}

sub shrink_jpg {
  my ($in, $out, $max) = @_;
  if ($max && (my $s = find_tool('sips'))) {
    my $dims = `"$s" -g pixelWidth -g pixelHeight "$in" 2>/dev/null`;
    my ($w) = $dims =~ /pixelWidth:\s*(\d+)/; my ($h) = $dims =~ /pixelHeight:\s*(\d+)/;
    my $side = ($w && $h) ? ($w > $h ? $w : $h) : 0;
    # Alleen verkleinen als de afbeelding groter is dan de doelmaat, zoals het echte programma (geen opschalen).
    return 1 if $side > $max && system("\"$s\" -Z $max \"$in\" --out \"$out\" >/dev/null 2>&1") == 0 && -s $out;
  }
  return copy($in, $out);
}

